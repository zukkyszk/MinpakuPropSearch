# 都道府県名付き表記も正規化して登録（例: "東京都新宿区" → pref="東京都", key="新宿区"）
_FQNAME_TABLE: dict[str, tuple[str, str]] = {}
for _city, _pref in _CITY_TO_PREF.items():
    _FQNAME_TABLE[_pref + _city] = (_pref, _city)


def parent_pref(area: str) -> Optional[str]:
    """
    エリア名から親都道府県名を返す。
    - "東京都"        → "東京都"
    - "新宿区"        → "東京都"
    - "東京都新宿区"  → "東京都"
    - 不明            → None
    """
    area = area.strip()
    if area in PREF_NAMES:
        return area
    if area in _FQNAME_TABLE:
        return _FQNAME_TABLE[area][0]
    if area in _CITY_TO_PREF:
        return _CITY_TO_PREF[area]
    # 前方一致で都道府県名を取り出す
    for pref in PREF_NAMES:
        if area.startswith(pref):
            return pref
    return None


def filter_key(area: str) -> Optional[str]:
    """
    住所フィルタに使う文字列を返す。
    都道府県そのものなら None（フィルタなし）、市区町村名なら区市町村名。

    例:
      "東京都"       → None
      "新宿区"       → "新宿区"
      "東京都新宿区" → "新宿区"
      "大阪市中央区" → "大阪市中央区"
    """
    area = area.strip()
    if area in PREF_NAMES:
        return None
    # 都道府県名を除いた残りが市区町村
    if area in _FQNAME_TABLE:
        return _FQNAME_TABLE[area][1]
    if area in _CITY_TO_PREF:
        return area
    for pref in PREF_NAMES:
        if area.startswith(pref):
            remainder = area[len(pref):]
            return remainder if remainder else None
    return area  # 解決できなければそのまま使ってフィルタ


def group_by_pref(areas: list[str]) -> dict[str, list[Optional[str]]]:
    """
    エリアリストを都道府県でグループ化する。
    戻り値: {都道府県: [住所フィルタキー, ...]}
      フィルタキーが None のものがあれば都道府県全体（フィルタなし）を意味する。

    例:
      ["新宿区", "渋谷区", "大阪市中央区"]
        → {"東京都": ["新宿区", "渋谷区"], "大阪府": ["大阪市中央区"]}
      ["東京都", "渋谷区"]
        → {"東京都": [None]}  ← None があるので全件（渋谷区フィルタ不要）
    """
    groups: dict[str, list[Optional[str]]] = defaultdict(list)
    for area in areas:
        pref = parent_pref(area)
        if pref is None:
            continue
        key = filter_key(area)
        groups[pref].append(key)

    # None（全件）が含まれる都道府県はフィルタを外す
    return {
        pref: ([None] if None in keys else keys)
        for pref, keys in groups.items()
    }


def address_in_area(address: str, filter_keys: list[Optional[str]]) -> bool:
    """
    物件の住所がフィルタキーのいずれかに一致するか判定する。
    filter_keys に None が含まれる場合は常に True。
    """
    if None in filter_keys:
        return True
    return any(k and k in address for k in filter_keys)
